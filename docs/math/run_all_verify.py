"""Run every docs/math/verify_*.py and write docs/math/verify-status.md.

    uv run python docs/math/run_all_verify.py

Each script runs in its own process from the repo root (as its docstring says) with a timeout.
Exit code is 1 if any script fails, so this can gate CI.
"""
from __future__ import annotations

import datetime
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TIMEOUT_S = 1200


def main() -> int:
    rows, failed = [], 0
    for f in sorted(HERE.glob("verify_*.py")):
        t0 = time.time()
        try:
            r = subprocess.run([sys.executable, str(f)], cwd=ROOT, capture_output=True, text=True, timeout=TIMEOUT_S)
            ok, tail = r.returncode == 0, (r.stdout + r.stderr).strip().splitlines()[-1:] or [""]
        except subprocess.TimeoutExpired:
            ok, tail = False, ["timed out"]
        failed += not ok
        rows.append((f.name, ok, time.time() - t0, tail[0][:90]))
        print(f"{'PASS' if ok else 'FAIL'}  {f.name}  ({rows[-1][2]:.1f}s)")
    stamp = datetime.date.today().isoformat()
    lines = [
        "# Verify status", "",
        f"*Generated by [`run_all_verify.py`](run_all_verify.py) on {stamp}. "
        f"{len(rows) - failed}/{len(rows)} scripts pass.*", "",
        "| script | result | seconds | last line of output |", "|---|---|---|---|",
    ]
    for name, ok, secs, last in rows:
        lines.append(f"| [`{name}`]({name}) | {'PASS' if ok else '**FAIL**'} | {secs:.1f} | {last.replace('|', '/')} |")
    (HERE / "verify-status.md").write_text("\n".join(lines) + "\n")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
