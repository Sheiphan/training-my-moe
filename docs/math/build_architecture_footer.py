def mermaid(n: int, highlight: bool = True) -> str:
    """Cumulative diagram at doc `n`. Colour = era the box was introduced in;
    amber with a thick border = introduced by doc `n` itself."""
    vis = [k for k in NODES if _visible(k, n)]
    lines = ["```mermaid", INIT, "flowchart TB"]
    if highlight:
        title, adds, _, _ = DOCS[n]
        lines += [
            f'  subgraph G_doc["{n:03d} · {title}"]',
            f'    DESC["<b>What this doc adds:</b><br/>{_wrap(adds)}"]',
            "  end",
        ]
    for gid, gtitle in GROUPS:
        members = [k for k in vis if NODES[k][2] == gid]
        if not members:
            continue
        lines.append(f'  subgraph G_{gid}["{gtitle}"]')
        for k in members:
            lines.append(f'    {k}["{NODES[k][0]}"]')
        lines.append("  end")
    for k in vis:
        if NODES[k][2] == "none":
            lines.append(f'  {k}["{NODES[k][0]}"]')
    for a, b, label, style, until in EDGES:
        if a in vis and b in vis and (until is None or n <= until):
            lines.append(f"  {a} {style}|{label}| {b}" if label else f"  {a} {style} {b}")
    if highlight:
        lines.append("  DESC ~~~ " + next(k for k in vis if NODES[k][2] != "none"))
    lines += class_defs()
    new = [k for k in vis if NODES[k][1] == n] if highlight else []
    for key, *_ in ERAS:
        members = [k for k in vis if k not in new and NODES[k][2] != "none" and era(NODES[k][1]) == key]
        if members:
            lines.append(f"  class {','.join(members)} {key}")
    if new:
        lines.append(f"  class {','.join(new)} cur")
    if highlight:
        lines.append("  class DESC desc")
    lines.append("```")
    return "\n".join(lines)


