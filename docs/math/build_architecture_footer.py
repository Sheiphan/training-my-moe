def _strip(text: str, a: str, b: str) -> str:
    while a in text:
        i = text.index(a)
        j = text.index(b, i) + len(b)
        text = text[:i].rstrip("\n") + "\n\n" + text[j:].lstrip("\n")
    return text


def _insert_before(text: str, heading_re: str, block: str) -> str:
    m = re.search(heading_re, text, re.M)
    assert m, heading_re
    return text[: m.start()] + block + "\n\n" + text[m.start():]


def _insert_after_line(text: str, heading_re: str, block: str) -> str:
    m = re.search(heading_re, text, re.M)
    assert m, heading_re
    return text[: m.end()] + "\n\n" + block + text[m.end():]


