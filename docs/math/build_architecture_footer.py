import re  # noqa: E402


def code_ref(node: str) -> tuple[str, int] | None:
    """(repo-relative path, 1-based line) of the node's defining line."""
    if node not in REFS:
        return None
    path, pat = REFS[node]
    for i, line in enumerate((ROOT / path).read_text().splitlines(), 1):
        if re.search(pat, line):
            return path, i
    raise AssertionError(f"{node}: pattern {pat!r} not found in {path}")


def journal_file(n: int) -> str:
    m = sorted((ROOT / "journey_of_a_model").glob(f"{n:03d}-*.md"))
    assert len(m) == 1, (n, m)
    return m[0].name


def links(node: str, base: str) -> dict[str, str]:
    """Markdown-ready links for a node. `base` is the page's path to docs/math."""
    n = NODES[node][1]
    out: dict[str, str] = {}
    if node != "INX":
        anc = step_anchor(node)
        if anc:
            text = anc[1] if len(anc[1]) <= 52 else anc[1][:49] + "..."
            out["math"] = f"[{n:03d} · {text}]({base}{_slug(n)}#{anc[0]})"
        else:
            out["math"] = f"[math {n:03d}]({base}{_slug(n)})"
        out["journal"] = f"[journal {n:03d}]({base}../../journey_of_a_model/{journal_file(n)})"
    ref = code_ref(node)
    if ref:
        path, line = ref
        out["code"] = f"[`{path}:{line}`]({base}../../{path}#L{line})"
    return out


def component_table(nodes: list[str], base: str = "") -> list[str]:
    rows = ["| component | math doc (section) | journal | code |", "|---|---|---|---|"]
    for k in nodes:
        if k == "INX":
            continue
        l = links(k, base)
        label = NODES[k][0].split("<br/>")[0]
        rows.append(f"| {label} | {l['math']} | {l['journal']} | {l.get('code', '')} |")
    return rows


