def _gh_slug(heading: str) -> str:
    import re as _re
    t = heading.lstrip("#").strip().lower()
    t = _re.sub(r"[^\w\- ]", "", t)
    return t.replace(" ", "-")


def step_anchor(node: str) -> tuple[str, str] | None:
    """(github-style anchor, plain heading text) for the node's best section, or None."""
    if node not in STEPS:
        return None
    n = NODES[node][1]
    seen: dict[str, int] = {}
    hit = None
    in_fence = False
    for line in (HERE / _slug(n)).read_text().splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        if in_fence or not line.startswith("#"):
            continue
        slug = _gh_slug(line)
        k = seen.get(slug, 0)
        seen[slug] = k + 1
        if hit is None and re.search(STEPS[node], line):
            hit = (slug if k == 0 else f"{slug}-{k}", re.sub(r"[`*$]", "", line.lstrip("#").strip()))
    assert hit, f"{node}: no heading matches {STEPS[node]!r} in doc {n:03d}"
    return hit


def _slug(n: int) -> str:
    matches = sorted(HERE.glob(f"{n:03d}-*.md"))
    assert len(matches) == 1, (n, matches)
    return matches[0].name


def _visible(node: str, n: int) -> bool:
    _, intro, _, until = NODES[node]
    return intro <= n and (until is None or n <= until)


