ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from configs import presets  # noqa: E402
from qwenmoe.model.rmsnorm import RMSNorm  # noqa: E402
from qwenmoe.model.transformer import QwenMoEModel  # noqa: E402
from qwenmoe.train.scaling import count_params  # noqa: E402

PRESET = "SCALE_300M"
OVERRIDES = dict(vocab_size=4097, max_seq_len=1024)  # journal 044's H100 run
OUT = ROOT / "site" / "model-figure"
SVG_NAME = "qwenmoe-scale-300m.svg"



def build():
    cfg = dataclasses.replace(getattr(presets, PRESET), **OVERRIDES)
    with torch.device("meta"):
        model = QwenMoEModel(cfg)
    counts = count_params(model)
    blk = model.blocks[0]
    n = lambda mod: sum(p.numel() for p in mod.parameters())  # noqa: E731
    eps = next(m for m in model.modules() if isinstance(m, RMSNorm)).eps
    return cfg, counts, {
        "attn": n(blk.attn),
        "moe": n(blk.moe),
        "expert": n(blk.moe.routed_experts[0]),
        "router": n(blk.moe.router),
        "emb": model.embedding.weight.numel(),
        "eps": eps,
    }


def f(x: int) -> str:
    return f"{x:,}"


ENGINE = ROOT / "site" / "shared" / "qwenmoe-model.js"
BASE_FIELDS = ("d_model", "n_heads", "n_kv_heads", "n_routed_experts", "top_k", "d_ff",
               "vocab_size", "n_layers", "max_seq_len", "rope_theta")


def run_engine(expr: str, payload):
    """Evaluate `expr` against site/shared/qwenmoe-model.js in Node (QM = the engine, A = payload).
    The figure is drawn by that one engine, so this page and the interactive tensor walk can
    never disagree about what the model looks like."""
    import json
    import shutil
    import subprocess

    node = shutil.which("node")
    if not node:
        raise SystemExit("this script needs `node` on PATH (it runs site/shared/qwenmoe-model.js)")
    code = f"const QM=require(process.argv[1]);const A=JSON.parse(process.argv[2]);console.log(JSON.stringify({expr}))"
    out = subprocess.run([node, "-e", code, str(ENGINE), json.dumps(payload)], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def engine_svg(cfg) -> str:
    base = {k: getattr(cfg, k) for k in BASE_FIELDS}
    return run_engine(f"QM.drawFigure(A, QM.DEFAULT, 0, {json_str(f'QwenMoE · {PRESET}')})", base)


def json_str(x: str) -> str:
    import json
    return json.dumps(x)


