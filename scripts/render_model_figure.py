def page(cfg, counts, extra, svg: str) -> str:
    fields = ["vocab_size", "d_model", "n_layers", "n_heads", "n_kv_heads", "d_ff", "n_routed_experts", "top_k",
              "n_shared_experts", "max_seq_len", "positional_scheme", "rope_theta", "qk_norm", "activation",
              "router_scoring", "moe_balancing", "aux_loss_weight", "attention_variant", "tie_word_embeddings",
              "mtp_depth", "init_std"]
    rows = "".join(f"<tr><td><code>{k}</code></td><td>{html.escape(str(getattr(cfg, k)))}</td></tr>" for k in fields)
    prow = lambda k, v: f"<tr><td>{k}</td><td class='n'>{f(v)}</td></tr>"  # noqa: E731
    params = "".join([
        prow("Token embedding (shared with the output layer)", counts.embedding),
        prow(f"Attention, all {cfg.n_layers} blocks", counts.attention_total),
        prow(f"Mixture of Experts, all {cfg.n_layers} blocks", counts.moe_total),
        prow("One routed expert", extra["expert"]),
        prow("One router", extra["router"]),
        prow("<strong>Total</strong>", counts.total),
        prow("<strong>Active per token</strong>", counts.active),
        prow("Active per token, excluding the embedding", counts.active - counts.embedding),
    ])
    return (PAGE.replace("__SVG__", svg).replace("__SVG_NAME__", SVG_NAME).replace("__PRESET__", PRESET)
            .replace("__LAYERS__", str(cfg.n_layers)).replace("__CFG__", rows).replace("__PARAMS__", params))


def main() -> None:
    cfg, counts, extra = build()
    svg = engine_svg(cfg)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / SVG_NAME).write_text(svg + "\n")
    (OUT / "index.html").write_text(page(cfg, counts, extra, svg))
    print(f"wrote {OUT / SVG_NAME} and {OUT / 'index.html'}  "
          f"(total {f(counts.total)}, active {f(counts.active)})")


if __name__ == "__main__":
    main()
