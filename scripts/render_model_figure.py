"""Draw the paper-style architecture figure for the latest trained model.

    uv run python scripts/render_model_figure.py

Writes site/model-figure/qwenmoe-scale-300m.svg (standalone, for READMEs and slides) and
site/model-figure/index.html (the figure plus the numbers behind it).

The figure is drawn by site/shared/qwenmoe-model.js (run through Node), the same engine the
interactive tensor walk uses. Every number on it is read from the real code: the config is configs/presets.py's
SCALE_300M with the overrides scripts/train.py applied for the H100 run in journal 044
(the FineWeb-Edu BPE tokenizer's vocab_size and a 1,024-token context), and the parameter
counts come from qwenmoe.train.scaling.count_params on a model built on the meta device
(shapes only, no memory). Change the preset or the overrides below and re-run.
"""
from __future__ import annotations

import dataclasses
